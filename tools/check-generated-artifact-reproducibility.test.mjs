#!/usr/bin/env node
/**
 * The falsifier suite of `tools/check-generated-artifact-reproducibility.mjs`, driven through the gate's own exported
 * decisions with a fabricated tree: the population scan, the undeclared-artefact finding, the line-and-member reading
 * of a mismatch, the three dispositions and the two blocking reasons.
 *
 * Nothing here runs a real producer. The producers' invocations are injected, because the question each case asks is
 * what the gate DECIDES from a reading, not whether `dotnet` is installed.
 *
 * red-proof: inject  the `inputs/` exclusion removed -> the pinned copy becomes a claimant: `examined 9 · undeclared 3` with `generated_artifact_without_producer:` naming `inputs/action-projection-source/.../action-surface.v1.json`, exit 1 (measured 2026-11-13)
 * red-proof: inject  `describeMismatch` answering with two byte counts -> `✖ the mismatch reading names the artefact's own line and the members on each side`, actual `(bytes)` where `$.a` was expected, exit 1 (measured 2026-11-13)
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";

import {
  classifyPopulation,
  describeMismatch,
  discoverClaimants,
  firstDifferingByte,
  headerClaimsDerivation,
  inputsMovedSince,
  runGate,
} from "./check-generated-artifact-reproducibility.mjs";

const DAY = 24 * 60 * 60 * 1000;

function tree(files) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "generated-artefact-"));
  for (const [relative, content] of Object.entries(files)) {
    const absolute = path.join(root, relative);
    fs.mkdirSync(path.dirname(absolute), { recursive: true });
    fs.writeFileSync(absolute, content);
  }
  return root;
}

/** An artefact older than every input, so nothing is skipped for staleness. */
function age(root, relative, days) {
  const absolute = path.join(root, relative);
  const when = new Date(Date.now() - days * DAY);
  fs.utimesSync(absolute, when, when);
}

function producerFor(artefact, { bytes, disposition, inputs = [] } = {}) {
  return {
    artefact,
    producer: "fake producer",
    disposition,
    run: { kind: "stdout", command: "fake", args: [] },
    requires: { commands: [], paths: [] },
    inputs,
    bytes,
  };
}

/** A `run` that answers with the producer entry's own declared bytes. */
function runFor(producers) {
  const byArtefact = new Map(producers.map((entry) => [entry.artefact, entry]));
  return (command, args) => {
    for (const entry of byArtefact.values()) {
      if (entry.run.kind !== "stdout") continue;
      return { status: 0, stdout: Buffer.from(entry.bytes ?? ""), stderr: Buffer.alloc(0), error: null };
    }
    return { status: 0, stdout: Buffer.alloc(0), stderr: Buffer.alloc(0), error: null };
  };
}

test("the population is every tracked claimant, minus the pinned-input tree", () => {
  const tracked = [
    "integrations/x/contracts/generated/a.v1.json",
    "integrations/x/contracts/projection/b.v1.json",
    "integrations/x/inputs/action-projection-source/contracts/generated/a.v1.json",
    "tools/notes.md",
  ];
  const root = tree({
    "integrations/x/contracts/generated/a.v1.json": "{}\n",
    "integrations/x/contracts/projection/b.v1.json": "{}\n",
  });
  const { claimants, pinnedInputs } = discoverClaimants({
    root,
    tracked,
    producers: [{ artefact: "integrations/x/contracts/projection/b.v1.json" }],
  });
  assert.deepEqual(
    claimants.map((claimant) => `${claimant.claim}:${claimant.path}`),
    ["path:integrations/x/contracts/generated/a.v1.json", "declared:integrations/x/contracts/projection/b.v1.json"],
  );
  assert.equal(pinnedInputs.length, 1, "a copy pinned under inputs/ is named, not counted as an artefact");
  assert.match(pinnedInputs[0].reason, /pinned under an inputs\/ tree/u);
});

test("a header marker claims derivation for three lines and prose below does not", () => {
  const root = tree({
    "header-first.md": "// GENERATED FILE - do not edit\nbody\n",
    "header-third.md": "\n# AUTO-GENERATED from the catalog\nbody\n",
    "prose-body.md": "intro\n\n\n// GENERATED by the tool, according to this document\n",
    "no-claim.md": "# notes\nwe derived this from the catalog\n",
  });
  assert.equal(headerClaimsDerivation(path.join(root, "header-first.md")), true);
  assert.equal(headerClaimsDerivation(path.join(root, "header-third.md")), true);
  assert.equal(
    headerClaimsDerivation(path.join(root, "prose-body.md")),
    false,
    "a marker on line 4 is prose about the tool, not a claim about this file",
  );
  assert.equal(headerClaimsDerivation(path.join(root, "no-claim.md")), false);
});

test("an artefact that claims derivation and has no producer is a finding, not a pass", () => {
  const root = tree({ "c/generated/orphan.v1.json": "{}\n" });
  const outcome = runGate(root, { tracked: ["c/generated/orphan.v1.json"], producers: [], run: runFor([]) });
  assert.equal(outcome.code, 1);
  assert.match(outcome.stderr, /generated_artifact_without_producer:c\/generated\/orphan\.v1\.json/u);
  const report = JSON.parse(outcome.stdout.trim().split("\n").pop());
  assert.equal(report.status, "failed");
  assert.equal(report.examined, 1);
  assert.equal(report.undeclared, 1);
});

test("a producer declared for a path no artefact carries is named, so a declaration cannot outlive it", () => {
  const root = tree({ "c/generated/kept.v1.json": "{}\n" });
  const producers = [
    producerFor("c/generated/kept.v1.json", { bytes: "{}\n" }),
    producerFor("c/generated/gone.v1.json", { bytes: "{}\n" }),
  ];
  const outcome = runGate(root, { tracked: ["c/generated/kept.v1.json"], producers, run: runFor(producers) });
  assert.equal(outcome.code, 1);
  assert.match(outcome.stderr, /declared_producer_without_artefact:c\/generated\/gone\.v1\.json/u);
});

test("a reproducible artefact passes and reports one measured item", () => {
  const artefact = "c/generated/kept.v1.json";
  const root = tree({ [artefact]: '{"actions":["a","b"]}\n' });
  const producers = [producerFor(artefact, { bytes: '{"actions":["a","b"]}\n' })];
  const outcome = runGate(root, { tracked: [artefact], producers, run: runFor(producers) });
  assert.equal(outcome.code, 0);
  assert.match(outcome.stdout, /artefacts examined 1 · with a declared producer 1 · undeclared 0/u);
  assert.match(outcome.stdout, new RegExp(`reproduced:${artefact} \\(22 bytes from fake producer\\)`, "u"));
});

test("a drifted artefact is named by line and member, never by a byte count", () => {
  const artefact = "c/generated/drifted.v1.json";
  const produced =
    JSON.stringify({ actions: [{ actionId: "a" }, { actionId: "b" }], host: ["x", "sweep_scythe"] }, null, 2) + "\n";
  const drifted =
    JSON.stringify({ actions: [{ actionId: "a" }, { actionId: "retired" }], host: ["x"] }, null, 2) + "\n";
  const root = tree({ [artefact]: drifted });
  const producers = [producerFor(artefact, { bytes: produced })];
  const outcome = runGate(root, { tracked: [artefact], producers, run: runFor(producers) });
  assert.equal(outcome.code, 1);
  assert.match(outcome.stderr, /generated_artifact_not_reproducible:c\/generated\/drifted\.v1\.json:\d+:\$\.actions/u);
  assert.match(outcome.stderr, /sweep_scythe/u, "names the member that moved, not the size difference");
  assert.match(outcome.stderr, /retired/u);
  assert.doesNotMatch(outcome.stderr, /bytes/u);
});

test("the mismatch reading names the artefact's own line and the members on each side", () => {
  const produced = Buffer.from(
    '{\n  "actions": [\n    {\n      "actionId": "use_mine_ladder"\n    }\n  ],\n  "host": [\n    "sweep_scythe"\n  ]\n}\n',
  );
  const artefact = Buffer.from(
    '{\n  "actions": [\n    {\n      "actionId": "break_container_source"\n    }\n  ],\n  "host": []\n}\n',
  );
  const reading = describeMismatch({ producedBytes: produced, artefactBytes: artefact });
  assert.equal(reading.line, 4, "the artefact's first differing line is the hand-edited action id");
  assert.equal(reading.member, "$.actions by actionId");
  assert.match(reading.detail, /break_container_source/u);
  assert.match(reading.detail, /use_mine_ladder/u);
  assert.match(
    reading.detail,
    /\$\.host: the producer emits 1 member\(s\) the artefact does not carry: "sweep_scythe"/u,
  );
});

test("identical bytes have no mismatch, and a one-byte difference is still a line and a member", () => {
  const same = Buffer.from('{"a":1}\n');
  assert.equal(describeMismatch({ producedBytes: same, artefactBytes: same }), null);
  assert.equal(firstDifferingByte(same, same), -1);
  const longer = Buffer.from('{"a":1}\n\n');
  assert.equal(firstDifferingByte(longer, same), 8);
  const reading = describeMismatch({ producedBytes: Buffer.from('{"a":2}\n'), artefactBytes: same });
  assert.equal(reading.line, 1);
  assert.equal(reading.member, "$.a");
});

test("a declared_by_test artefact is its own bucket: never reproduced, never a failure", () => {
  const artefact = "c/generated/sample.v1.json";
  const root = tree({ [artefact]: '{"sample":true}\n' });
  const producers = [producerFor(artefact, { bytes: '{"other":true}\n', disposition: "declared_by_test" })];
  const outcome = runGate(root, { tracked: [artefact], producers, run: runFor(producers) });
  assert.equal(outcome.code, 0);
  assert.match(outcome.stdout, new RegExp(`not_re_derived:declared_by_test:${artefact}`, "u"));
  const report = JSON.parse(outcome.stdout.trim().split("\n").pop());
  assert.equal(report.declaredByTest, 1);
  assert.equal(report.reproduced, 0);
  assert.equal(report.findings, 0);
});

test("an artefact whose inputs did not move is not re-derived, and one whose input moved is", () => {
  const artefact = "c/generated/fresh.v1.json";
  const input = "c/source.cs";
  const root = tree({ [artefact]: '{"a":1}\n', [input]: "class Source {}\n" });
  age(root, artefact, 1);
  age(root, input, 2);
  const entry = producerFor(artefact, { bytes: '{"a":1}\n', inputs: [input] });
  assert.deepEqual(inputsMovedSince({ root, entry, artefact: path.join(root, artefact) }).reason, "inputs_unchanged");
  age(root, input, 0);
  const moved = inputsMovedSince({ root, entry, artefact: path.join(root, artefact) });
  assert.equal(moved.moved, true);
  assert.match(moved.reason, /^input_newer:c\/source\.cs$/u);
});


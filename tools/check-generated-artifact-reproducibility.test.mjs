test("a run that measured nothing is blocked, and the population counts are printed", () => {
  const outcome = runGate(process.cwd(), { tracked: [], producers: [], run: runFor([]) });
  assert.equal(outcome.code, 2);
  assert.match(outcome.stderr, /generated-artifact-reproducibility_blocked:no_artefact_claims_derivation/u);
  const report = JSON.parse(outcome.stdout.trim().split("\n").pop());
  assert.equal(report.examined, 0);
  assert.equal(report.status, "blocked");
});

test("the report carries the population field the shared judge reads", () => {
  const artefact = "c/generated/kept.v1.json";
  const root = tree({ [artefact]: "{}\n" });
  const producers = [producerFor(artefact, { bytes: "{}\n" })];
  const report = JSON.parse(
    runGate(root, { tracked: [artefact], producers, run: runFor(producers) })
      .stdout.trim()
      .split("\n")
      .pop(),
  );
  assert.equal(typeof report.examined, "number");
  assert.equal(report.gate, "generated-artifact-reproducibility");
  assert.deepEqual(
    report.checks.map((check) => check.id),
    [
      "generated_artifact_without_producer",
      "generated_artifact_not_reproducible",
      "declared_producer_without_artefact",
      "generated_artifact_producer_unavailable",
    ],
  );
});

test("classifyPopulation counts the three buckets it prints", () => {
  const claimants = [
    { path: "c/generated/declared.v1.json", claim: "path" },
    { path: "c/generated/test.v1.json", claim: "path" },
    { path: "c/generated/orphan.v1.json", claim: "path" },
  ];
  const producers = [
    producerFor("c/generated/declared.v1.json"),
    producerFor("c/generated/test.v1.json", { disposition: "declared_by_test" }),
  ];
  assert.deepEqual(classifyPopulation({ claimants, producers }), {
    examined: 3,
    declaredProducer: 2,
    undeclared: ["c/generated/orphan.v1.json"],
    declaredByTest: 1,
    declaredProducersWithoutArtefact: [],
  });
});

test("an artefact with no declared input is re-derived rather than skipped", () => {
  const artefact = "c/generated/undeclared-inputs.v1.json";
  const root = tree({ [artefact]: '{"a":1}\n' });
  age(root, artefact, 1);
  const entry = producerFor(artefact, { bytes: '{"a":1}\n', inputs: [] });
  const reading = inputsMovedSince({ root, entry, artefact: path.join(root, artefact) });
  assert.equal(reading.moved, true, "a producer whose inputs nobody declared cannot be skipped on staleness");
  assert.equal(reading.reason, "no_declared_input_resolved");
});

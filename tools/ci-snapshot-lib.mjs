import { createHash, randomUUID } from "node:crypto";
import { chmod, constants, copyFile, lstat, mkdir, readFile, realpath, rename, rm, writeFile } from "node:fs/promises";
import { basename, dirname, isAbsolute, join, normalize, relative, resolve, sep } from "node:path";

export const SNAPSHOT_SCHEMA = "gamebuddy-no-commit-clean-room-snapshot/v1";
export const REQUIRED_INPUTS_SCHEMA = "gamebuddy-required-snapshot-inputs/v2";
export const REQUIRED_INPUT_REFERENCE_REQUIREMENT =
  "must be proven by a tracked build or CI reference before admission";
export const REQUIRED_INPUT_REFERENCE_MARKER_PREFIX = "gamebuddy-snapshot-input:";
export const SNAPSHOT_CONTROL_OWNER = "snapshot-tooling";
export const SNAPSHOT_CONTROL_PURPOSE = "required-input control";
export const REQUIRED_INPUTS_PATH = ".ci/required-snapshot-inputs.json";

export const sha256 = (value) => createHash("sha256").update(value).digest("hex");
// Git records regular files as 100644/100755. Windows does not expose POSIX
// read/write bits faithfully through lstat, so use the portable Git mode while
// retaining executable-bit identity when it is observable.
const canonicalMode = (state) => ((state.mode & 0o111) === 0 ? 0o644 : 0o755);
const slash = (value) => value.replaceAll("\\", "/");
const snapshotError = (code) => new Error(`ci_snapshot_${code}`);
const comparePaths = (left, right) => (left < right ? -1 : left > right ? 1 : 0);

async function git(root, args) {
  const { spawn } = await import("node:child_process");
  return await new Promise((resolveOutput, rejectOutput) => {
    const child = spawn("git", args, { cwd: root, stdio: ["ignore", "pipe", "pipe"] });
    const chunks = [];
    const errors = [];
    child.stdout.on("data", (chunk) => chunks.push(Buffer.from(chunk)));
    child.stderr.on("data", (chunk) => errors.push(Buffer.from(chunk)));
    child.once("error", rejectOutput);
    child.once("close", (code) =>
      code === 0
        ? resolveOutput(Buffer.concat(chunks))
        : rejectOutput(new Error(`git_${args[0]}_failed:${Buffer.concat(errors).toString("utf8")}`)),
    );
  });
}

export function assertSafeRelativePath(value, code = "path_invalid") {
  if (
    typeof value !== "string" ||
    value.length === 0 ||
    value.includes("\\") ||
    value.includes(":") ||
    value.includes("\0")
  )
    throw snapshotError(code);
  if (
    isAbsolute(value) ||
    value.startsWith("/") ||
    value.split("/").some((part) => part.length === 0 || part === "." || part === "..")
  )
    throw snapshotError(code);
  return value;
}

function assertNonSecretInput(input) {
  const segments = input.path.toLowerCase().split("/");
  if (
    segments.some(
      (segment) =>
        segment === ".env" || segment.startsWith(".env.") || /(?:credential|secret|token|private.?key)/.test(segment),
    )
  )
    throw snapshotError("required_input_secret_path_forbidden");
}

function assertNonSecretBytes(bytes) {
  const text = bytes.toString("utf8");
  if (
    /-----BEGIN(?: [A-Z0-9]+)? PRIVATE KEY-----|(?:^|[^A-Za-z0-9_])(gh[pous]_[A-Za-z0-9]{20,}|sk-[A-Za-z0-9_-]{16,})(?:$|[^A-Za-z0-9_-])/m.test(
      text,
    )
  )
    throw snapshotError("required_input_secret_content_forbidden");
}

function inside(root, candidate, code) {
  const relation = relative(root, candidate);
  if (isAbsolute(relation) || relation === ".." || relation.startsWith(`..${sep}`)) throw snapshotError(code);
}

async function regularFile(path, code, { rejectHardlinks = true } = {}) {
  let state;
  try {
    state = await lstat(path);
  } catch (error) {
    if (error?.code === "ENOENT") throw snapshotError(code);
    throw error;
  }
  if (state.isSymbolicLink() || !state.isFile() || (rejectHardlinks && state.nlink !== 1)) throw snapshotError(code);
  return state;
}

function exactKeys(value, keys) {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    Object.getPrototypeOf(value) === Object.prototype &&
    Object.getOwnPropertySymbols(value).length === 0 &&
    JSON.stringify(Object.keys(value).sort()) === JSON.stringify([...keys].sort())
  );
}

export function classifyCandidatePaths(paths, inputs) {
  const declared = new Map(inputs.map((input) => [input.path, input]));
  const candidates = paths
    .map((path) => {
      const normalized = typeof path === "string" ? path.replace(/\/+$/, "") : path;
      return assertSafeRelativePath(normalized, "untracked_path_invalid");
    })
    .sort(comparePaths)
    .map((path) => {
      const input = declared.get(path);
      if (path === REQUIRED_INPUTS_PATH)
        return Object.freeze({
          path,
          classification: "snapshot_control",
          owner: SNAPSHOT_CONTROL_OWNER,
          purpose: SNAPSHOT_CONTROL_PURPOSE,
          referenceRequirement: "generated by the snapshot tooling; not a runtime input",
        });
      if (input)
        return Object.freeze({
          path,
          classification: "snapshot_input",
          owner: input.owner,
          purpose: input.purpose,
          referenceRequirement: input.referenceRequirement,
        });
      const excluded =
        EXCLUDED_CANDIDATE_NAMES.has(path) || EXCLUDED_CANDIDATE_PREFIXES.some((prefix) => path.startsWith(prefix));
      return Object.freeze({
        path,
        classification: excluded ? "excluded" : "unclassified",
        owner: null,
        purpose: null,
        referenceRequirement: REQUIRED_INPUT_REFERENCE_REQUIREMENT,
      });
    });
  return Object.freeze(candidates);
}

const EXCLUDED_CANDIDATE_PREFIXES = Object.freeze([
  ".agents/",
  ".claude/",
  ".commit-snapshots/",
  ".commit-validation/",
  ".pi/",
  ".worktree/",
  "design/",
  "docs/",
  "ref/",
  "research/",
]);
const EXCLUDED_CANDIDATE_NAMES = new Set(["HANDOFF.md", "contentprobe.err", "contentprobe.out"]);

export function assertRequiredInputDescriptor(input, code = "required_inputs_invalid") {
  if (
    !exactKeys(input, ["path", "owner", "purpose", "type", "mode", "sha256", "referencedBy", "referenceRequirement"]) ||
    input.type !== "file" ||
    typeof input.owner !== "string" ||
    input.owner.trim().length === 0 ||
    typeof input.purpose !== "string" ||
    input.purpose.trim().length === 0 ||
    !Number.isInteger(input.mode) ||
    ![0o644, 0o755].includes(input.mode) ||
    !/^[a-f0-9]{64}$/.test(input.sha256) ||
    !Array.isArray(input.referencedBy) ||
    input.referencedBy.length === 0 ||
    typeof input.referenceRequirement !== "string" ||
    input.referenceRequirement.trim().length === 0
  )
    throw snapshotError(code);
  const safePath = assertSafeRelativePath(input.path, code);
  const references = input.referencedBy.map((reference) => {
    if (
      !exactKeys(reference, ["path", "marker"]) ||
      typeof reference.marker !== "string" ||
      reference.marker !== `${REQUIRED_INPUT_REFERENCE_MARKER_PREFIX}${safePath}`
    )
      throw snapshotError(code);
    return Object.freeze({ path: assertSafeRelativePath(reference.path, code), marker: reference.marker });
  });
  const referencePaths = references.map((reference) => reference.path);
  if (
    new Set(referencePaths).size !== referencePaths.length ||
    new Set(referencePaths.map((path) => path.toLocaleLowerCase("en-US"))).size !== referencePaths.length ||
    referencePaths.some((path, index) => index > 0 && comparePaths(path, referencePaths[index - 1]) < 0)
  )
    throw snapshotError(code);
  const normalized = Object.freeze({ ...input, path: safePath, referencedBy: Object.freeze(references) });
  assertNonSecretInput(normalized);
  return normalized;
}

async function assertTrackedReferences(root, input) {
  const rows = await trackedRows(root);
  const tracked = new Set(rows.filter((row) => !row.deleted).map((row) => row.path));
  for (const reference of input.referencedBy) {
    if (!tracked.has(reference.path)) throw snapshotError("required_input_reference_untracked");
    const path = resolve(root, reference.path);
    inside(root, path, "required_input_reference_escapes_root");
    await regularFile(path, "required_input_reference_invalid");
    const content = (await readFile(path, "utf8")).replaceAll("\\r\\n", "\\n");
    if (!content.includes(reference.marker)) throw snapshotError("required_input_reference_missing");
  }
}

export async function readRequiredInputs(root) {
  const path = resolve(root, REQUIRED_INPUTS_PATH);
  await regularFile(path, "required_inputs_invalid", { rejectHardlinks: false });
  let value;
  try {
    value = JSON.parse(await readFile(path, "utf8"));
  } catch {
    throw snapshotError("required_inputs_invalid");
  }
  if (
    !exactKeys(value, ["schema", "inputs"]) ||
    value.schema !== REQUIRED_INPUTS_SCHEMA ||
    !Array.isArray(value.inputs)
  )
    throw snapshotError("required_inputs_invalid");
  const inputs = value.inputs.map((input) => assertRequiredInputDescriptor(input));
  const paths = inputs.map((entry) => entry.path);
  const foldedPaths = paths.map((path) => path.toLocaleLowerCase("en-US"));
  if (
    new Set(paths).size !== paths.length ||
    new Set(foldedPaths).size !== foldedPaths.length ||
    paths.some((path, index) => index > 0 && comparePaths(path, paths[index - 1]) < 0)
  )
    throw snapshotError("required_inputs_invalid");
  for (const input of inputs) await assertTrackedReferences(root, input);
  return Object.freeze(inputs);
}

export async function verifyRequiredInputs(root, inputs) {
  const verified = [];
  const resolvedInputs = inputs ?? (await readRequiredInputs(root));
  for (const input of resolvedInputs) {
    const path = resolve(root, input.path);
    inside(root, path, "required_input_escapes_root");
    const state = await regularFile(path, "required_input_invalid", { rejectHardlinks: false });
    const bytes = await readFile(path);
    assertNonSecretBytes(bytes);
    if (sha256(bytes) !== input.sha256 || canonicalMode(state) !== input.mode)
      throw snapshotError("required_input_identity_mismatch");
    verified.push(Object.freeze({ path: input.path, type: "file", mode: canonicalMode(state), sha256: sha256(bytes) }));
  }
  return Object.freeze(verified);
}

export async function fileIdentity(root, path, code = "file_invalid") {
  const safePath = assertSafeRelativePath(path, code);
  const absolute = resolve(root, safePath);
  inside(root, absolute, code);
  const state = await regularFile(absolute, code);
  return Object.freeze({
    path: safePath,
    type: "file",
    mode: canonicalMode(state),
    sha256: sha256(await readFile(absolute)),
  });
}

export async function collectUntrackedCandidates(root, inputs) {
  const raw = await git(root, ["ls-files", "--others", "--exclude-standard", "-z"]);
  return classifyCandidatePaths(raw.toString("utf8").split("\0").filter(Boolean), inputs);
}

async function trackedRows(root) {
  const output = await git(root, ["ls-files", "-s", "-z"]);
  const deleted = new Set(
    (await git(root, ["diff", "--name-only", "--diff-filter=D", "-z"])).toString("utf8").split("\0").filter(Boolean),
  );
  return output
    .toString("utf8")
    .split("\0")
    .filter(Boolean)
    .map((record) => {
      const match = /^(\d+) ([0-9a-f]{40}) (\d+)\t(.+)$/.exec(record);
      if (!match || match[3] !== "0") throw snapshotError("tracked_index_invalid");
      const path = assertSafeRelativePath(slash(match[4]), "tracked_index_invalid");
      return Object.freeze({ path, mode: Number.parseInt(match[1], 8) & 0o777, deleted: deleted.has(path) });
    })
    .sort((left, right) => comparePaths(left.path, right.path));
}

export async function createSourceManifest(root) {
  const rows = await trackedRows(root);
  const inputs = await readRequiredInputs(root);
  const required = await verifyRequiredInputs(root, inputs);
  const control = await fileIdentity(root, REQUIRED_INPUTS_PATH, "required_inputs_invalid");
  const reserved = new Set([control.path, ...required.map((entry) => entry.path)]);
  const tracked = [];
  for (const row of rows) {
    if (row.deleted) continue;
    if (reserved.has(row.path)) {
      if (row.path !== control.path) throw snapshotError("required_input_must_be_untracked");
      continue;
    }
    const path = resolve(root, row.path);
    inside(root, path, "tracked_path_escapes_root");
    const state = await regularFile(path, "tracked_path_invalid", { rejectHardlinks: false });
    if (canonicalMode(state) !== row.mode) throw snapshotError("tracked_mode_mismatch");
    tracked.push(Object.freeze({ path: row.path, type: "file", mode: row.mode, sha256: sha256(await readFile(path)) }));
  }
  const entries = [...tracked, control, ...required].sort((left, right) => comparePaths(left.path, right.path));
  const paths = entries.map((entry) => entry.path);
  if (
    new Set(paths).size !== entries.length ||
    new Set(paths.map((path) => path.toLocaleLowerCase("en-US"))).size !== entries.length
  )
    throw snapshotError("source_manifest_duplicate_path");
  return Object.freeze({
    entries,
    digest: sha256(JSON.stringify(entries)),
    requiredInputsConfig: control,
    requiredInputs: required,
  });
}

export function assertSnapshotManifest(value) {
  if (
    !exactKeys(value, [
      "schema",
      "baseCommit",
      "trackedPatchSha256",
      "untrackedReportSha256",
      "requiredInputsConfig",
      "requiredInputs",
      "source",
    ]) ||
    value.schema !== SNAPSHOT_SCHEMA ||
    !/^[0-9a-f]{40}$/.test(value.baseCommit) ||
    !/^[a-f0-9]{64}$/.test(value.trackedPatchSha256) ||
    !/^[a-f0-9]{64}$/.test(value.untrackedReportSha256) ||
    !exactKeys(value.requiredInputsConfig, ["path", "type", "mode", "sha256"]) ||
    value.requiredInputsConfig.path !== REQUIRED_INPUTS_PATH ||
    value.requiredInputsConfig.type !== "file" ||
    !Number.isInteger(value.requiredInputsConfig.mode) ||
    ![0o644, 0o755].includes(value.requiredInputsConfig.mode) ||
    !/^[a-f0-9]{64}$/.test(value.requiredInputsConfig.sha256) ||
    !Array.isArray(value.requiredInputs) ||
    !exactKeys(value.source, ["digest", "entries"]) ||
    !/^[a-f0-9]{64}$/.test(value.source.digest) ||
    !Array.isArray(value.source.entries)
  )
    throw snapshotError("manifest_invalid");
  try {
    const inputs = value.requiredInputs.map((input) => assertRequiredInputDescriptor(input, "manifest_invalid"));
    const paths = inputs.map((input) => input.path);
    if (
      new Set(paths).size !== paths.length ||
      new Set(paths.map((path) => path.toLocaleLowerCase("en-US"))).size !== paths.length ||
      paths.some((path, index) => index > 0 && comparePaths(path, paths[index - 1]) < 0)
    )
      throw snapshotError("manifest_invalid");
    for (const entry of value.source.entries) {
      if (
        !exactKeys(entry, ["path", "type", "mode", "sha256"]) ||
        entry.type !== "file" ||
        !Number.isInteger(entry.mode) ||
        ![0o644, 0o755].includes(entry.mode) ||
        !/^[a-f0-9]{64}$/.test(entry.sha256)
      )
        throw snapshotError("manifest_invalid");
      assertSafeRelativePath(entry.path, "manifest_invalid");
    }
    const sourcePaths = value.source.entries.map((entry) => entry.path);
    if (
      new Set(sourcePaths).size !== sourcePaths.length ||
      new Set(sourcePaths.map((path) => path.toLocaleLowerCase("en-US"))).size !== sourcePaths.length ||
      sourcePaths.some((path, index) => index > 0 && comparePaths(path, sourcePaths[index - 1]) < 0) ||
      sha256(JSON.stringify(value.source.entries)) !== value.source.digest
    )
      throw snapshotError("manifest_invalid");
  } catch (error) {
    if (error?.message === "ci_snapshot_manifest_invalid") throw error;
    throw snapshotError("manifest_invalid");
  }
  return value;
}

async function copyOrVerify({ sourceRoot, destinationRoot, input, code }) {
  const source = resolve(sourceRoot, input.path);
  const destination = resolve(destinationRoot, input.path);
  inside(sourceRoot, source, "required_input_escapes_root");
  inside(destinationRoot, destination, "required_input_escapes_root");
  const sourceState = await regularFile(source, "required_input_invalid");
  const sourceBytes = await readFile(source);
  assertNonSecretBytes(sourceBytes);
  if (canonicalMode(sourceState) !== input.mode || sha256(sourceBytes) !== input.sha256)
    throw snapshotError("required_input_identity_mismatch");
  await mkdir(dirname(destination), { recursive: true, mode: 0o700 });
  try {
    await copyFile(source, destination, constants.COPYFILE_EXCL);
    await chmod(destination, input.mode);
  } catch (error) {
    if (error?.code !== "EEXIST") throw error;
  }
  const copied = await regularFile(destination, code);
  if (canonicalMode(copied) !== input.mode || sha256(await readFile(destination)) !== input.sha256)
    throw snapshotError(code);
}

export async function copyVerifiedRequiredInputs({ sourceRoot, destinationRoot, inputs, control }) {
  await copyOrVerify({ sourceRoot, destinationRoot, input: control, code: "required_inputs_config_copy_mismatch" });
  for (const input of inputs)
    await copyOrVerify({ sourceRoot, destinationRoot, input, code: "required_input_copy_mismatch" });
}

export async function writeSnapshotManifest(path, value) {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  await writeFile(path, `${JSON.stringify(value, null, 2)}\n`, { encoding: "utf8", mode: 0o600, flag: "wx" });
}

/** The materialized worktree may have staged snapshot changes; it must have no
 * unstaged difference or non-ignored untracked residue. */
export async function assertFrozenSnapshotIndex(root) {
  try {
    await git(root, ["diff", "--quiet"]);
  } catch {
    throw snapshotError("materialized_tree_dirty");
  }
  const untracked = await git(root, ["ls-files", "--others", "--exclude-standard", "-z"]);
  if (untracked.length !== 0) throw snapshotError("materialized_tree_untracked");
}

export async function assertCanonicalDirectory(path, code) {
  const state = await lstat(path);
  if (state.isSymbolicLink() || !state.isDirectory()) throw snapshotError(code);
  const canonical = await realpath(path);
  if (normalize(canonical) !== normalize(resolve(path))) throw snapshotError(code);
  return canonical;
}

/**
 * Validate and, when necessary, create an output parent without traversing a
 * symlinked directory. The nearest existing ancestor is checked before mkdir;
 * this matters when the requested parent itself does not exist yet.
 */
export async function prepareCanonicalOutputParent(outputPath, code = "output_root_invalid") {
  const output = resolve(outputPath);
  const parent = dirname(output);
  let ancestor = parent;
  while (true) {
    try {
      await lstat(ancestor);
      break;
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
      const next = dirname(ancestor);
      if (next === ancestor) throw snapshotError(code);
      ancestor = next;
    }
  }
  await assertCanonicalDirectory(ancestor, code);
  await mkdir(parent, { recursive: true, mode: 0o700 });
  await assertCanonicalDirectory(parent, code);
  return Object.freeze({ output, parent });
}

/**
 * Reserve an output transaction in a private sibling directory. Callers must
 * commit it only after all evidence has been written and verified. The final
 * output is never visible in a partially-written state.
 */
export async function prepareTransactionalOutput(outputPath, code = "output_root_invalid", { create = true } = {}) {
  const prepared = await prepareCanonicalOutputParent(outputPath, code);
  try {
    await lstat(prepared.output);
    throw snapshotError("output_exists");
  } catch (error) {
    if (error?.message === "ci_snapshot_output_exists") throw error;
    if (error?.code !== "ENOENT") throw error;
  }
  for (let attempt = 0; attempt < 8; attempt += 1) {
    const temporary = join(prepared.parent, `.${basename(prepared.output)}.tmp-${process.pid}-${randomUUID()}`);
    try {
      if (create) {
        await mkdir(temporary, { recursive: false, mode: 0o700 });
        await assertCanonicalDirectory(temporary, code);
      }
      return Object.freeze({ ...prepared, temporary });
    } catch (error) {
      if (error?.code === "EEXIST") continue;
      throw error;
    }
  }
  throw snapshotError("temporary_output_unavailable");
}

/** Remove only a still-canonical directory at the exact tool-owned temp path. */
export async function cleanupTransactionalOutput(transaction) {
  if (!transaction?.temporary || !transaction?.parent) return;
  try {
    await assertCanonicalDirectory(transaction.parent, "output_root_invalid");
    await assertCanonicalDirectory(transaction.temporary, "temporary_output_invalid");
  } catch {
    // Never recursively remove a path which was replaced by a symlink, file,
    // or directory outside the prepared parent.
    return;
  }
  await rm(transaction.temporary, { recursive: true, force: true, maxRetries: 2, retryDelay: 50 });
}

export async function commitTransactionalOutput(transaction) {
  // POSIX rename(2) replaces an existing empty directory, so the existence
  // check below cannot provide a no-overwrite guarantee against a competing
  // creator. Node does not expose a portable rename-no-replace directory
  // primitive. The supported snapshot/release platform is therefore explicit:
  // Windows MoveFileEx (via fs.rename) refuses an existing destination.
  if (process.platform !== "win32") throw snapshotError("transactional_output_unsupported_platform");
  await assertCanonicalDirectory(transaction.parent, "output_root_invalid");
  await assertCanonicalDirectory(transaction.temporary, "temporary_output_invalid");
  try {
    await lstat(transaction.output);
    throw snapshotError("output_exists");
  } catch (error) {
    if (error?.message === "ci_snapshot_output_exists") throw error;
    if (error?.code !== "ENOENT") throw error;
  }
  try {
    // On Windows this is the no-overwrite finalization boundary: if a
    // competing destination appears after the lstat above, rename rejects it
    // rather than replacing it. This is not a portable POSIX guarantee.
    await rename(transaction.temporary, transaction.output);
  } catch (error) {
    if (error?.code === "EEXIST" || error?.code === "ENOTEMPTY" || error?.code === "EPERM")
      throw snapshotError("output_exists");
    throw error;
  }
  await assertCanonicalDirectory(transaction.output, "output_root_invalid");
}

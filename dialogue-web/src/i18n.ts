export function resolveLocale(): Locale {
  const saved = localStorage.getItem("gamebuddy.tavern.ui-locale");
  if (saved === "en" || saved === "zh-CN") return saved;
  return [...(navigator.languages ?? []), navigator.language].some((value) => value?.toLowerCase().startsWith("zh"))
    ? "zh-CN"
    : "en";
}

export function messages(locale: Locale): Messages {
  return locale === "zh-CN" ? zh : en;
}
export function setLocale(locale: Locale): void {
  localStorage.setItem("gamebuddy.tavern.ui-locale", locale);
  document.documentElement.lang = locale === "zh-CN" ? "zh-CN" : "en";
}

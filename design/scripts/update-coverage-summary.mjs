#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const coveragePath = path.join(root, "migration/semantic-coverage.csv");
const summaryPath = path.join(root, "migration/semantic-coverage-summary.md");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (quoted) {
      if (char === '"' && text[index + 1] === '"') { cell += '"'; index += 1; }
      else if (char === '"') quoted = false;
      else cell += char;
    } else if (char === '"') quoted = true;
    else if (char === ",") { row.push(cell); cell = ""; }
    else if (char === "\n") { row.push(cell.replace(/\r$/, "")); if (row.some(Boolean)) rows.push(row); row = []; cell = ""; }
    else cell += char;
  }
  return rows;
}

const rows = parseCsv(await readFile(coveragePath, "utf8"));
const header = rows.shift();
const columns = Object.fromEntries(header.map((name, index) => [name, index]));
const counts = { unreviewed: 0, "in-review": 0, reviewed: 0, accepted: 0 };
for (const row of rows) counts[row[columns.review_status]] += 1;
const sourceCount = new Set(rows.map((row) => row[columns.old_path])).size;
const summary = `---
id: MIGRATION-SEMANTIC-COVERAGE-SUMMARY
type: migration-record
status: current
owner: documentation
---

# 语义覆盖审计状态

<!-- generated by scripts/update-coverage-summary.mjs; do not edit counts manually -->

## 结论

**新文档尚未被证明完整表达旧文档。** 本页是覆盖审计的状态记录，不是产品规范，也不把机械生成的章节清单当作语义证据。

## 已完成的机械工作

- \`migration/document-inventory.csv\` 登记 ${sourceCount} 份旧 Markdown。
- \`migration/semantic-coverage.csv\` 已按旧资料的 Markdown 标题展开为 ${rows.length.toLocaleString("en-US")} 条章节记录。
- 每条记录都保留旧逻辑路径、章节标题、候选 current owner、审计状态和 gap 字段。
- 检查器逐项比较 archive 标题与 ledger 章节 multiset；它不会因为记录存在就宣称语义覆盖。

## 当前审计状态

| 状态 | 章节记录 | 含义 |
|---|---:|---|
| \`unreviewed\` | ${counts.unreviewed.toLocaleString("en-US")} | 只有机械章节标题和待审 gap，不能作为覆盖证据 |
| \`in-review\` | ${counts["in-review"].toLocaleString("en-US")} | 已开始章节审阅但尚未完成独立复核 |
| \`reviewed\` | ${counts.reviewed.toLocaleString("en-US")} | 章节映射已完成，等待接受 |
| \`accepted\` | ${counts.accepted.toLocaleString("en-US")} | owner 与独立 reviewer 均接受 |

## 审计规则

只有同时满足以下条件，章节才能进入 \`reviewed\` 或 \`accepted\`：

1. 逐章写明对应的 current 文档和章节；
2. 逐章记录保留的约束，而不是只写“已合并”；
3. 明确记录删除、降级为历史或被 supersede 的内容及理由；
4. 对没有 current owner 的内容记录 gap、owner、下一步和阻塞原因；
5. 通过对应领域 owner 与独立 reviewer 的复核。

## 审计顺序

1. Game / Stardew：产品身份、Game Action、capability coverage、native provenance、安装、bootstrap、恢复和发布门。
2. Chat / Tavern / Memory / Voice：界面隔离、continuity、Magic Context、Memory authority、兼容和语音降级。
3. Runtime / Desktop / Security / Operations：进程、凭据、停止/恢复、发布声明、测试证据和运维。
4. cross-cutting、implementation plan、research 和 review：区分长期规则、执行细节、研究结论、证据记录和历史背景。

在所有章节记录达到 \`reviewed\` 或 \`accepted\` 前，不得把“文档迁移完成”解释为“语义等价迁移完成”。
`;
await writeFile(summaryPath, summary, "utf8");
console.log(JSON.stringify({ sources: sourceCount, records: rows.length, counts }));
